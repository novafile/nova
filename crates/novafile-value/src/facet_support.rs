//! facet integration for the value types (feature `facet`).
//!
//! [`Timestamp`], [`Duration`], [`Decimal`] and [`Rational`] derive `Facet`
//! as opaque types with a `String` proxy, and [`Value`] is described as an
//! opaque type. The NOVA facet binding (`novafile-facet`) recognizes all five by
//! their shape and maps them to the corresponding NOVA kinds losslessly. Other
//! facet formats see the four scalar kinds *naturally*, through the proxy, as
//! their canonical text (as with serde); `Value` itself has no natural form
//! outside NOVA.

use crate::{Decimal, Duration, Rational, Timestamp, Value};

macro_rules! text_proxy {
    ($($t:ty),*) => {$(
        impl TryFrom<String> for $t {
            type Error = String;
            fn try_from(s: String) -> Result<Self, String> {
                <$t>::parse(&s)
            }
        }

        impl From<&$t> for String {
            fn from(v: &$t) -> Self {
                v.to_string()
            }
        }
    )*};
}

text_proxy!(Timestamp, Duration, Decimal, Rational);

// `Value` is recursive and has no explicit `repr`, which the derive requires
// of enums, so it is described by hand as an opaque type, the way facet itself
// describes foreign types.
//
// SAFETY: the shape is built by `ShapeBuilder::for_sized::<Value>`, so its
// type id and layout are those of `Value`; the vtable and type operations are
// generated by facet's own macros for `Value`. Being opaque, the shape exposes
// no fields or variants that reflection could misuse.
unsafe impl facet::Facet<'_> for Value {
    const SHAPE: &'static facet::Shape = &const {
        const VTABLE: facet::VTableDirect = facet::vtable_direct!(Value => Debug, PartialEq);
        const OPS: facet::TypeOpsDirect = facet::type_ops_direct!(Value => Clone);
        facet::ShapeBuilder::for_sized::<Value>("Value")
            .module_path("novafile_value")
            .ty(facet::Type::User(facet::UserType::Opaque))
            .def(facet::Def::Undefined)
            .vtable_direct(&VTABLE)
            .type_ops_direct(&OPS)
            .send()
            .sync()
            .build()
    };
}
